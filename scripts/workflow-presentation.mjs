import { createHash } from "node:crypto";
import { build } from "../packages/frontend/node_modules/esbuild/lib/main.js";
import { readFile, writeFile, unlink } from "node:fs/promises";
import { resolve } from "node:path";
import { format } from "../packages/frontend/node_modules/prettier/index.mjs";
const temporary = resolve(
  "packages/frontend/.workflow-presentation-catalog.mjs",
);
try {
  await build({
    entryPoints: ["packages/frontend/src/shared/presentation/catalog.ts"],
    bundle: true,
    platform: "node",
    format: "esm",
    packages: "external",
    outfile: temporary,
  });
  const { resultComponents, inputComponents } = await import(temporary);
  const { z } = await import("../packages/frontend/node_modules/zod/index.js");
  const schemas = (components) =>
    Object.fromEntries(
      Object.entries(components).map(([name, component]) => [
        name,
        z.toJSONSchema(component.props, { unrepresentable: "any" }),
      ]),
    );
  const catalogs = {
    "workflow-result-v1": schemas(resultComponents),
    "workflow-input-v1": schemas(inputComponents),
  };
  const descriptions = (components) =>
    Object.fromEntries(
      Object.entries(components).map(([name, component]) => [
        name,
        {
          description: component.description,
          slots: component.slots ?? [],
          example: component.example ?? null,
        },
      ]),
    );
  const canonical = (value) =>
    Array.isArray(value)
      ? value.map(canonical)
      : value && typeof value === "object"
        ? Object.fromEntries(
            Object.keys(value)
              .sort()
              .map((key) => [key, canonical(value[key])]),
          )
        : value;
  const digests = Object.fromEntries(
    Object.entries(catalogs).map(([version, value]) => [
      version,
      createHash("sha256")
        .update(JSON.stringify(canonical(value)))
        .digest("hex"),
    ]),
  );
  const outputs = {
    "server/internal/workflow/dsl/presentation-catalog.generated.json":
      JSON.stringify(
        {
          catalogs,
          descriptions: {
            "workflow-result-v1": descriptions(resultComponents),
            "workflow-input-v1": descriptions(inputComponents),
          },
          digests,
        },
        null,
        2,
      ) + "\n",
    "packages/frontend/src/shared/presentation/catalog-digests.generated.ts":
      "// Code generated by workflow-presentation. DO NOT EDIT.\nexport const catalogDigests = " +
      JSON.stringify(digests, null, 2) +
      " as const;\n",
  };
  for (const [path, rawOutput] of Object.entries(outputs)) {
    const output = await format(rawOutput, { filepath: path });
    if (process.argv.includes("--check")) {
      if ((await readFile(path, "utf8")) !== output)
        throw new Error("Run pnpm workflow:presentation:generate");
    } else await writeFile(path, output);
  }
} finally {
  await unlink(temporary).catch(() => {});
}
