// error-catalog 从应用错误唯一权威生成前端本地化目录。
package main

import (
	"encoding/json"

	"github.com/JieWaZi/NeuxBot/server/constants/status_error"
	"os"
)

func main() {
	catalog := map[string]map[string]any{}
	for lang, messages := range status_error.MessageTemplates() {
		for identity, message := range messages {
			entry := catalog[identity.Key()]
			if entry == nil {
				entry = map[string]any{"code": identity.Code()}
				catalog[identity.Key()] = entry
			}

			entry[lang] = message
		}
	}
	encoded, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		panic(err)
	}
	output := "// Code generated by go run ./cmd/error-catalog. DO NOT EDIT!\nexport const statusErrorCatalog = " + string(encoded) + ";\n"
	if len(os.Args) != 2 {
		panic("expected output path")
	}
	if err := os.WriteFile(os.Args[1], []byte(output), 0644); err != nil {
		panic(err)
	}
}
