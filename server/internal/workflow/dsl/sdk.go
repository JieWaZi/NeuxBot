//go:embed generated/*
var sdkFiles embed.FS

// SDKArtifact 读取生成并随 Core 打包的创作知识，不声明虚假的宿主全局函数。
func SDKArtifact(name string) string {
	data, err := sdkFiles.ReadFile("generated/" + name)
	if err != nil {
		return ""
	}
	return string(data)
}

// PrimitiveContract 是创作声明、编译与宿主绑定共同使用的契约项。
type PrimitiveContract struct {
	// Name 是原生源码中的调用名称。
	Name string `json:"name"`
	// Signature 是生成给创作的精确声明。
	Signature string `json:"signature"`
	// AwaitRequired 表示调用必须等待结果。
	AwaitRequired bool `json:"awaitRequired"`
	// HostCapability 是需要实现的宿主效果名称。
	HostCapability string `json:"hostCapability"`
}

// Registry 返回有确定顺序的原生 SDK 契约。
