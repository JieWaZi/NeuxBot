package controllers

import (
	"context"
	"fmt"
	"strings"

	"github.com/JieWaZi/NeuxBot/server/constants/status_error"
	"github.com/JieWaZi/NeuxBot/server/repositories/models"
	"github.com/google/uuid"
	"github.com/shrewx/ginx/pkg/dbhelper"
	"gorm.io/gorm"
	"gorm.io/gorm/clause"
)

// usageProjectionFormat changes when replay must recover missing projected facts.
const usageProjectionFormat = "providers-v2:"

// UsageController manages the disposable terminal usage projection.
type UsageController struct {
	// db uses the existing business SQLite pool.
	db *gorm.DB
	// transactions commit projection batches with source progress.
	transactions TransactionController
}

func NewUsageController(db *gorm.DB) *UsageController {
	return &UsageController{db: db, transactions: NewTransactionController(dbhelper.NewGormTransactionManager(db))}
}

func (c *UsageController) Checkpoints(ctx context.Context) ([]models.UsageCheckpoint, error) {
	db := controllerDB(ctx, c.db)
	var checkpoints []models.UsageCheckpoint
	read := func() error { return db.Order("shard").Find(&checkpoints).Error }
	if err := read(); err != nil {
		return nil, databaseError("read_usage_checkpoints", "", err)
	}
	if len(checkpoints) == 0 || !strings.HasPrefix(checkpoints[0].Generation, usageProjectionFormat) {
		// Re-read under the same transaction that retires the derived projection.
		// Concurrent readers cannot reset a generation another reader just installed.
		if err := c.transactions.Transaction(ctx, func(ctx context.Context) error {
			db := controllerDB(ctx, c.db)
			var marker models.UsageCheckpoint
			if err := db.Where("shard = -1").Limit(1).Find(&marker).Error; err != nil {
				return err
			}
			if strings.HasPrefix(marker.Generation, usageProjectionFormat) {
				return nil
			}
			if err := db.Where("1 = 1").Delete(&models.UsageRecord{}).Error; err != nil {
				return err
			}
			if err := db.Where("1 = 1").Delete(&models.UsageCheckpoint{}).Error; err != nil {
				return err
			}
			return db.Create(&models.UsageCheckpoint{Shard: -1, Generation: usageProjectionFormat + uuid.NewString()}).Error
		}); err != nil {
			return nil, err
		}
		if err := read(); err != nil {
			return nil, databaseError("read_usage_checkpoints", "", err)
		}
	}
	if len(checkpoints) == 0 || checkpoints[0].Shard != -1 || checkpoints[0].Generation == "" {
		return nil, status_error.DatabaseError
	}
	return checkpoints, nil
}

// Generation reads the current projection generation. An empty value invalidates snapshots.
func (c *UsageController) Generation(ctx context.Context) (string, error) {
	var marker models.UsageCheckpoint
	err := controllerDB(ctx, c.db).Where("shard = -1").Limit(1).Find(&marker).Error
	if err != nil {
		return "", databaseError("read_usage_generation", "", err)
	}
	return marker.Generation, nil
}

// Project inserts each invocation once and advances the stream cursor atomically.
func (c *UsageController) Project(ctx context.Context, generation string, shard int, cursor int64, records []models.UsageRecord) error {
	return c.transactions.Transaction(ctx, func(ctx context.Context) error {
		db := controllerDB(ctx, c.db)
		var marker models.UsageCheckpoint
		if err := db.Where("shard = -1").Take(&marker).Error; err != nil {
			return err
		}
		if marker.Generation != generation {
			return fmt.Errorf("usage projection generation changed")
		}
		if len(records) > 0 {
			// GORM fills autogenerated IDs on insert. Each transaction attempt
			// starts from an unmodified batch.
			rows := append([]models.UsageRecord(nil), records...)
			if err := db.Clauses(clause.OnConflict{Columns: []clause.Column{{Name: "native_id"}}, DoNothing: true}).
				CreateInBatches(rows, 64).Error; err != nil {
				return err
			}
		}
		return db.Clauses(clause.OnConflict{
			Columns: []clause.Column{{Name: "shard"}}, DoUpdates: clause.AssignmentColumns([]string{"cursor"}),
			Where: clause.Where{Exprs: []clause.Expression{clause.Expr{SQL: "usage_checkpoints.cursor < excluded.cursor"}}},
		}).Create(&models.UsageCheckpoint{Shard: shard, Cursor: cursor}).Error
	})
}

// ResetProjection clears derived rows and cursors for replay on the next read.
func (c *UsageController) ResetProjection(ctx context.Context) error {
	return c.transactions.Transaction(ctx, func(ctx context.Context) error {
		db := controllerDB(ctx, c.db)
		if err := db.Where("1 = 1").Delete(&models.UsageRecord{}).Error; err != nil {
			return err
		}
		return db.Where("1 = 1").Delete(&models.UsageCheckpoint{}).Error
	})
}

// UsageHighWater captures the insertion boundary and earliest retained terminal time.
func (c *UsageController) UsageHighWater(ctx context.Context) (int64, *int64, error) {
	db := controllerDB(ctx, c.db).Model(&models.UsageRecord{}).Session(&gorm.Session{})
	var last models.UsageRecord
	if err := db.Select("id").Order("id DESC").Limit(1).Find(&last).Error; err != nil {
		return 0, nil, databaseError("usage_high_water", "", err)
	}
	var first models.UsageRecord
	if err := db.Select("recorded_at").Where("id <= ?", last.ID).Order("recorded_at, id").Limit(1).Find(&first).Error; err != nil {
		return 0, nil, databaseError("usage_first_retained", "", err)
	}
	if last.ID == 0 {
		return 0, nil, nil
	}
	return last.ID, &first.RecordedAt, nil
}

// UsageQuery scopes a read to a time range and projection snapshot.
type UsageQuery struct {
	// From 是包含的时间下界。
	From int64
	// To 是排除的时间上界。
	To int64
	// HighWater 固定快照可见的最后一条投影记录。
	HighWater int64
	// WakerIDs 可按原始伙伴筛选。
	WakerIDs []string
	// ChatID 可按原始公开对话筛选。
	ChatID string
	// Provider 可按原生后端筛选。
	Provider string
	// AccountID 可按建立连接时的账号筛选。
	AccountID string
	// Source 可按原始调用入口筛选。
	Source string
}

func (c *UsageController) scoped(ctx context.Context, filter UsageQuery) *gorm.DB {
	db := controllerDB(ctx, c.db).Model(&models.UsageRecord{}).
		Where("recorded_at >= ? AND recorded_at < ? AND id <= ?", filter.From, filter.To, filter.HighWater)
	if len(filter.WakerIDs) > 0 {
		db = db.Where("waker_id IN ?", filter.WakerIDs)
	}
	if filter.ChatID != "" {
		db = db.Where("chat_id = ?", filter.ChatID)
	}
	if filter.Provider != "" {
		db = db.Where("provider = ?", filter.Provider)
	}
	if filter.AccountID != "" {
		db = db.Where("account_id = ?", filter.AccountID)
	}
	if filter.Source != "" {
		db = db.Where("source = ?", filter.Source)
	}
	return db
}

// Walk seeks through bounded batches in the time index.
func (c *UsageController) Walk(ctx context.Context, filter UsageQuery, visit func(models.UsageRecord) error) error {
	var at, id int64
	for {
		var rows []models.UsageRecord
		db := c.scoped(ctx, filter).Order("recorded_at, id").Limit(repositoryReadBatch)
		if id != 0 {
			db = db.Where("(recorded_at, id) > (?, ?)", at, id)
		}
		if err := db.Find(&rows).Error; err != nil {
			return databaseError("walk_usage", "", err)
		}
		for _, row := range rows {
			if err := visit(row); err != nil {
				return err
			}
			at, id = row.RecordedAt, row.ID
		}
		if len(rows) < repositoryReadBatch {
			return nil
		}
	}
}

// UsageGroupKey identifies a group and distinguishes model IDs across providers.
type UsageGroupKey struct {
	// Key 是分组维度的原始标识。
	Key string
	// Provider 是模型分组对应的原生后端，其他维度留空。
	Provider string
}

// GroupKeys counts groups and seeks the next keys without materializing every group.
func (c *UsageController) GroupKeys(ctx context.Context, filter UsageQuery, group string, after *UsageGroupKey, limit int) (int64, []UsageGroupKey, error) {
	var column string
	switch group {
	case "model":
		return c.modelGroupKeys(ctx, filter, after, limit)
	case "waker":
		column = "waker_id"
	case "provider":
		column = "provider"
	default:
		return 0, nil, fmt.Errorf("unsupported usage group")
	}
	var total int64
	db := c.scoped(ctx, filter)
	if err := db.Distinct(column).Count(&total).Error; err != nil {
		return 0, nil, databaseError("count_usage_groups", "", err)
	}
	db = c.scoped(ctx, filter).Select("DISTINCT " + column + " AS key").Order(column).Limit(limit)
	if after != nil {
		db = db.Where(column+" > ?", after.Key)
	}
	var keys []UsageGroupKey
	if err := db.Scan(&keys).Error; err != nil {
		return 0, nil, databaseError("page_usage_groups", "", err)
	}
	return total, keys, nil
}

func (c *UsageController) modelGroupKeys(ctx context.Context, filter UsageQuery, after *UsageGroupKey, limit int) (int64, []UsageGroupKey, error) {
	var total int64
	groups := c.scoped(ctx, filter).Select("1").Group("model, provider")
	if err := controllerDB(ctx, c.db).Table("(?) AS usage_groups", groups).Count(&total).Error; err != nil {
		return 0, nil, databaseError("count_usage_groups", "", err)
	}
	db := c.scoped(ctx, filter).Select("DISTINCT model AS key, provider").Order("model, provider").Limit(limit)
	if after != nil {
		db = db.Where("(model, provider) > (?, ?)", after.Key, after.Provider)
	}
	var keys []UsageGroupKey
	if err := db.Scan(&keys).Error; err != nil {
		return 0, nil, databaseError("page_usage_groups", "", err)
	}
	return total, keys, nil
}
