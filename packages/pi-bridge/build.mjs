// 用固定的上游依赖构建 Pi 可加载的单文件桥，并收集实际打入文件的第三方许可。
import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const output = resolve(root, "../../resources/pi-bridge/bridge.mjs");
const licenseOutput = resolve(root, "../../resources/pi-bridge/MCP-LICENSES.txt");
const check = process.argv.includes("--check");
if (!check) await mkdir(dirname(output), {recursive:true});
const result = await build({
  absWorkingDir: root,
  entryPoints: [join(root, "entry.mjs")],
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  external: ["@earendil-works/*"],
  outfile: output,
  write: false,
  metafile: true,
  minify: true,
  supported: { "template-literal": false },
  legalComments: "eof",
  banner: {
    js: "// NeuxBot Pi bridge; generated by packages/pi-bridge/build.mjs. DO NOT EDIT.\n// Third-party licenses: MCP-LICENSES.txt.",
  },
});

const licenses = new Map();
for (const name of Object.keys(result.metafile.inputs)) {
  let directory = dirname(resolve(root, name));
  while (directory !== dirname(directory)) {
    try {
      const pkg = JSON.parse(
        await readFile(join(directory, "package.json"), "utf8"),
      );
      if (pkg.name && !licenses.has(pkg.name)) {
        let body = "";
        for (const file of [
          "LICENSE",
          "LICENSE.md",
          "LICENSE.txt",
          "license",
          "license.md",
          "COPYING",
        ]) {
          try {
            body = await readFile(join(directory, file), "utf8");
            break;
          } catch {
            // 部分包只在 package.json 中声明许可。
          }
        }
        licenses.set(
          pkg.name,
          `${pkg.name}@${pkg.version} (${pkg.license ?? "see package"})\n${body.replace(/[ \t]+$/gm, "")}`,
        );
      }
      break;
    } catch {
      directory = dirname(directory);
    }
  }
}

const artifacts = [
  [output, result.outputFiles[0].text],
  [
    licenseOutput,
    [...licenses.values()].sort().join("\n\n--------------------\n\n"),
  ],
];
for (const [path, content] of artifacts) {
  if (check) {
    if ((await readFile(path, "utf8")) !== content) {
      throw new Error(`Pi bridge 构建产物已过期：${path}`);
    }
  } else {
    await writeFile(path, content);
  }
}
process.stdout.write(
  `${check ? "Verified" : "Bundled"} ${licenses.size} Pi bridge packages\n`,
);
